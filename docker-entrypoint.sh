#!/bin/sh
# ============================================================================
# Docker Entrypoint - نوبت مارکت
# ============================================================================
# اجرای مایگریشن‌های Prisma قبل از شروع سرور Next.js
# ============================================================================

set -e

echo "🔄 در حال اجرای مایگریشن‌های دیتابیس..."

# اجرای مایگریشن با استفاده از prisma CLI
npx prisma db push --accept-data-loss 2>&1 || true

echo "✅ مایگریشن‌ها اجرا شدند"
echo "🚀 شروع سرور Next.js..."

# اجرای سرور Next.js
exec node server.js